
function results = summarize_results(data, models, psoResults, stability, sensitivity, pareto, settings)
%SUMMARIZE_RESULTS Save tables and a report-friendly engineering summary.

    results = struct();

    bestX = psoResults.bestX(:)';
    bestPred = psoResults.bestPred;

    optimumTable = table( ...
        bestX(1), bestX(2), bestX(3), ...
        bestPred.Rt, bestPred.Rz, bestPred.ToolWear, ...
        psoResults.bestObjective, ...
        'VariableNames', {'Vc_opt', 'f_opt', 'DOC_opt', 'Rt_pred', 'Rz_pred', 'ToolWear_pred', 'Objective'});

    results.optimumTable = optimumTable;
    writetable(optimumTable, fullfile(settings.tableDir, 'optimum_solution.csv'));

    % Save model metrics
    writetable(models.metricsTable, fullfile(settings.tableDir, 'model_metrics.csv'));

    % Save Pareto-style candidate tables
    writetable(pareto.all, fullfile(settings.tableDir, 'pareto_candidates.csv'));
    writetable(pareto.front, fullfile(settings.tableDir, 'pareto_front.csv'));

    % Engineering notes on repeatability
    meanRtStd = mean(data.analysisTable.Rt_std, 'omitnan');
    meanRzStd = mean(data.analysisTable.Rz_std, 'omitnan');
    meanTWStd = mean(data.analysisTable.ToolWear_std, 'omitnan');

    centerMask = abs(data.analysisTable.Vc - data.centerPoint(1)) < 1e-12 & ...
                 abs(data.analysisTable.f  - data.centerPoint(2)) < 1e-12 & ...
                 abs(data.analysisTable.DOC - data.centerPoint(3)) < 1e-12;

    if any(centerMask)
        centerRtMean = mean(data.analysisTable.Rt_avg(centerMask), 'omitnan');
        centerRzMean = mean(data.analysisTable.Rz_avg(centerMask), 'omitnan');
        centerTWMean = mean(data.analysisTable.ToolWear_avg(centerMask), 'omitnan');
    else
        centerRtMean = NaN;
        centerRzMean = NaN;
        centerTWMean = NaN;
    end

    % Sensitivity interpretation
    rankRows = sensitivity.rankingTable;

    % Short engineering interpretation of the optimum
    tradeoffNote = build_tradeoff_note(bestX, bestPred, settings);
    modelNote = build_model_note(models);

    summaryText = sprintf([ ...
        'AI-Driven Optimization of Dry CNC Milling using PSO\n', ...
        '==================================================\n\n', ...
        'Final optimal machining parameters:\n', ...
        '  Vc   = %.6f %s\n', ...
        '  f    = %.6f %s\n', ...
        '  DOC  = %.6f %s\n\n', ...
        'Predicted performance at the selected optimum:\n', ...
        '  Rt_avg       = %.6f um\n', ...
        '  Rz_avg       = %.6f um\n', ...
        '  ToolWear_avg = %.6f mm\n', ...
        '  Objective J  = %.6f\n\n', ...
        'Dataset summary:\n', ...
        '  Valid rows used             = %d\n', ...
        '  Unique design points        = %d\n', ...
        '  Repeated center points      = %d\n', ...
        '  Center point                = [%.6f, %.6f, %.6f]\n\n', ...
        'Repeatability notes:\n', ...
        '  mean(Rt_std)               = %.6f um\n', ...
        '  mean(Rz_std)               = %.6f um\n', ...
        '  mean(ToolWear_std)         = %.6f mm\n', ...
        '  Center-point mean Rt_avg   = %.6f um\n', ...
        '  Center-point mean Rz_avg   = %.6f um\n', ...
        '  Center-point mean ToolWear = %.6f mm\n\n', ...
        'Selected surrogate models:\n%s\n\n', ...
        'Sensitivity ranking (largest effect first):\n%s\n\n', ...
        'Trade-off interpretation:\n%s\n\n', ...
        'Model quality note:\n%s\n\n', ...
        'MRR note:\n', ...
        '  True MRR was not forced into the study because the workbook does not provide enough\n', ...
        '  cutter engagement geometry for a physically reliable MRR calculation.\n', ...
        '  The optimization therefore remains focused on Rt_avg, Rz_avg, and ToolWear_avg.\n'], ...
        bestX(1), settings.bounds.units{1}, ...
        bestX(2), settings.bounds.units{2}, ...
        bestX(3), settings.bounds.units{3}, ...
        bestPred.Rt, bestPred.Rz, bestPred.ToolWear, psoResults.bestObjective, ...
        data.numRows, data.numUniqueDesignPoints, data.centerPointCount, ...
        data.centerPoint(1), data.centerPoint(2), data.centerPoint(3), ...
        meanRtStd, meanRzStd, meanTWStd, ...
        centerRtMean, centerRzMean, centerTWMean, ...
        modelNote, table_to_text(rankRows), tradeoffNote, build_model_quality_note(models));

    summaryFile = fullfile(settings.outputRoot, 'engineering_summary.txt');
    fid = fopen(summaryFile, 'w');
    fprintf(fid, '%s', summaryText);
    fclose(fid);

    % Save a human-readable text file of model equations
    eqFile = fullfile(settings.modelDir, 'selected_model_equations.txt');
    fid = fopen(eqFile, 'w');
    fprintf(fid, 'Selected surrogate models\n');
    fprintf(fid, '=========================\n\n');

    modelNames = {'Rt', 'Rz', 'ToolWear'};
    for i = 1:numel(modelNames)
        mdl = models.(modelNames{i});
        fprintf(fid, '%s\n', mdl.responseName);
        fprintf(fid, '----------------------------------------\n');
        fprintf(fid, 'Model: %s\n', mdl.name);
        fprintf(fid, 'Fit type: %s\n', mdl.fitType);
        fprintf(fid, 'Train R2: %.6f\n', mdl.trainMetrics.R2);
        fprintf(fid, 'CV R2: %.6f\n', mdl.cvMetrics.R2);
        fprintf(fid, 'Reason: %s\n', mdl.reason);
        fprintf(fid, 'Equation / predictor:\n%s\n\n', mdl.equationString);
    end
    fclose(fid);

    results.summaryText = summaryText;
    results.summaryFile = summaryFile;
    results.modelEquationFile = eqFile;

    fprintf('\n--- Engineering summary saved ---\n%s\n', summaryFile);
end

function txt = build_tradeoff_note(bestX, bestPred, settings)
    lb = settings.bounds.lb;
    ub = settings.bounds.ub;
    positionText = cell(1, 3);

    for i = 1:3
        rel = (bestX(i) - lb(i)) / max(ub(i) - lb(i), eps);
        if rel < 1/3
            positionText{i} = 'low end of the allowable range';
        elseif rel > 2/3
            positionText{i} = 'high end of the allowable range';
        else
            positionText{i} = 'middle of the allowable range';
        end
    end

    txt = sprintf([ ...
        'The selected weighted optimum balances surface quality and tool wear within the feasible machining window. ', ...
        'The best solution places Vc near the %s, f near the %s, and DOC near the %s. ', ...
        'Predicted outputs at this point are Rt_avg = %.6f um, Rz_avg = %.6f um, and ToolWear_avg = %.6f mm. ', ...
        'This should be discussed together with the response surfaces, sensitivity sweeps, and PSO stability plots to explain the engineering trade-off clearly.'], ...
        positionText{1}, positionText{2}, positionText{3}, ...
        bestPred.Rt, bestPred.Rz, bestPred.ToolWear);
end

function txt = build_model_note(models)
    txt = sprintf([ ...
        'Rt_avg      -> %s\n', ...
        'Rz_avg      -> %s\n', ...
        'ToolWear_avg-> %s'], ...
        models.Rt.name, models.Rz.name, models.ToolWear.name);
end

function txt = build_model_quality_note(models)
    txt = sprintf([ ...
        'Rt_avg model CV R2      = %+0.4f\n', ...
        'Rz_avg model CV R2      = %+0.4f\n', ...
        'ToolWear_avg model CV R2= %+0.4f\n', ...
        'The roughness responses show noticeably higher scatter than tool wear, so roughness predictions should be reported with caution.'], ...
        models.Rt.cvMetrics.R2, models.Rz.cvMetrics.R2, models.ToolWear.cvMetrics.R2);
end

function txt = table_to_text(T)
    headers = T.Properties.VariableNames;
    txt = '';

    % Header line
    for i = 1:numel(headers)
        txt = [txt, sprintf('%-18s', headers{i})]; %#ok<AGROW>
    end
    txt = [txt, newline]; %#ok<AGROW>

    % Rows
    for r = 1:height(T)
        for c = 1:width(T)
            value = T{r, c};
            if isnumeric(value)
                if isscalar(value)
                    txt = [txt, sprintf('%-18.4f', value)]; %#ok<AGROW>
                else
                    txt = [txt, sprintf('%-18s', mat2str(value))]; %#ok<AGROW>
                end
            elseif iscell(value)
                txt = [txt, sprintf('%-18s', char(string(value{1})))]; %#ok<AGROW>
            else
                txt = [txt, sprintf('%-18s', char(string(value)))]; %#ok<AGROW>
            end
        end
        txt = [txt, newline]; %#ok<AGROW>
    end
end
